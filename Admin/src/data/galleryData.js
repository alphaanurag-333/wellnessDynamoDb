export function galleryCategoryClass(category = "") {
  const key = category.toLowerCase();
  if (key.includes("birthday")) return "birthday";
  if (key.includes("champion")) return "champion";
  if (key.includes("logo")) return "logo";
  if (key.includes("testimonial")) return "testimonials";
  if (key.includes("banner")) return "default";
  if (key.includes("audio")) return "audio";
  if (key.includes("video")) return "video";
  return "default";
}

export function galleryVersionLabel(count) {
  return `${count} version${count === 1 ? "" : "s"}`;
}
